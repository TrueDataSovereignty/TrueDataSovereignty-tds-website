"""Build data.js from the router's real output (web/how-it-works-data/cases-out.json).
Nothing here is written by hand: every field is copied from the capture. Re-run after a new capture."""
import json, pathlib
here = pathlib.Path(__file__).parent
src = here.parents[2] / "how-it-works-data" / "cases-out.json"
d = json.loads(src.read_text(encoding="utf-8"))
keep_audit = ["request_id", "policy_version", "task", "tier", "rule", "entity_counts", "generalised_counts", "handling", "destination", "model", "provider", "prev_hash"]
import re
def align(text, spans, sent):
    """Pair each span the router found with what the router put in its place. Only slices the router's own strings."""
    parts, pos, spos = [], 0, 0
    for i, s in enumerate(spans):
        lit = text[pos:s["start"]]
        assert sent[spos:spos + len(lit)] == lit, (lit, sent[spos:spos + 40])
        spos += len(lit); parts.append({"lit": lit})
        nxt = text[s["end"]:spans[i + 1]["start"] if i + 1 < len(spans) else len(text)]
        idx = sent.index(nxt, spos) if nxt else len(sent)
        b = sent[spos:idx]
        parts.append({"a": s["text"], "b": b, "type": s["type"], "kind": "masked" if b.startswith("⟦") else "widened"})
        spos, pos = idx, s["end"]
    parts.append({"lit": text[pos:]})
    assert "".join(q.get("lit", q.get("a", "")) for q in parts) == text
    assert "".join(q.get("lit", q.get("b", "")) for q in parts) == sent
    return parts
def align_answer(ph, real):
    """Pair each placeholder in the answer with what the router's unmask put back."""
    parts, rpos, last = [], 0, 0
    toks = list(re.finditer("⟦[^⟧]+⟧", ph))
    for i, m in enumerate(toks):
        lit = ph[last:m.start()]
        assert real[rpos:rpos + len(lit)] == lit
        rpos += len(lit); parts.append({"lit": lit})
        nxt = ph[m.end():toks[i + 1].start() if i + 1 < len(toks) else len(ph)]
        idx = real.index(nxt, rpos) if nxt else len(real)
        parts.append({"a": m.group(0), "b": real[rpos:idx]}); rpos, last = idx, m.end()
    parts.append({"lit": ph[last:]})
    assert "".join(q.get("lit", q.get("b", "")) for q in parts) == real
    return parts
cases = []
for c in d["cases"]:
    c["parts"] = align(c["text"], c.get("spans", []), c["sent"]) if c.get("sent") else [{"lit": c["text"]}] if not c.get("spans") else None
    if c["parts"] is None:  # kept local: mark what was found, nothing replaces it
        ps, pos = [], 0
        for s in c["spans"]:
            ps += [{"lit": c["text"][pos:s["start"]]}, {"a": s["text"], "b": None, "type": s["type"], "kind": "kept"}]; pos = s["end"]
        c["parts"] = ps + [{"lit": c["text"][pos:]}]
    c["ans_parts"] = align_answer(c["answer_with_placeholders"], c["answer_restored"]) if c.get("answer_with_placeholders") else None
    cases.append({
        "parts": c["parts"], "ans_parts": c["ans_parts"],
        "key": c["key"], "title": c["title"], "tier": c["tier"], "rule": c["rule"], "reason": c["reason"],
        "sent": c.get("sent") is not None,
        "audit": {k: c["audit"].get(k) for k in keep_audit},
    })
js = "/* Generated by make_data.py from web/how-it-works-data/cases-out.json. Real router output on synthetic text. Do not edit by hand. */\nvar TDS_DATA = " + json.dumps({"commit": d["commit"], "outbound_attempts": d["outbound_attempts"], "cases": cases}, ensure_ascii=False, separators=(",", ":")) + ";\n"
(here / "data.js").write_text(js, encoding="utf-8", newline="\n")
print("data.js", len(js.encode("utf-8")), "bytes;", len(cases), "cases; commit", d["commit"])
